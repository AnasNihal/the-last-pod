const ALIASES: Record<string, string> = { '–': '-', '—': '-', '’': "'", '‘': "'", '“': '"', '”': '"', '×': '✕' }

export type PixelOptions = {
  align?: 'left' | 'center' | 'right'; bold?: boolean
  shadow?: string; depth?: number; outline?: string; outlineWidth?: number
}
const glyphs = (text: string) => [...text.toUpperCase()].map(char => ALIASES[char] ?? char)
export const pixelAdvance = (scale: number, bold = false) => (bold ? 7 : 6) * scale
export const pixelWidth = (text: string, scale: number, bold = false) => {
  const count = glyphs(text).length
  return count ? count * pixelAdvance(scale, bold) - scale : 0
}

export function pixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string, options: PixelOptions = {}) {
  const chars = glyphs(text)
  const width = pixelWidth(text, scale, options.bold)
  const left = Math.round(options.align === 'center' ? x - width / 2 : options.align === 'right' ? x - width : x)
  const top = Math.round(y)
  const extra = options.bold ? scale : 0
  const path = new Path2D()
  chars.forEach((char, index) => {
    const rows = GLYPHS[char]
    if (!rows) return
    const gx = left + index * pixelAdvance(scale, options.bold)
    rows.forEach((row, r) => {
      for (let c = 0; c < 5; c++) if (row & (16 >> c)) path.rect(gx + c * scale, top + r * scale, scale + extra, scale)
    })
  })
  if (options.shadow && options.depth) {
    ctx.fillStyle = options.shadow
    for (let d = options.depth; d >= 1; d--) {
      ctx.save(); ctx.translate(d * .35, d); ctx.fill(path); ctx.restore()
    }
  }
  if (options.outline) {
    const o = options.outlineWidth ?? Math.max(1, Math.round(scale / 2))
    ctx.fillStyle = options.outline
    for (const [dx, dy] of [[-o, 0], [o, 0], [0, -o], [0, o], [-o, -o], [o, -o], [-o, o], [o, o]]) {
      ctx.save(); ctx.translate(dx, dy); ctx.fill(path); ctx.restore()
    }
  }
  ctx.fillStyle = color
  ctx.fill(path)
  return width
}
